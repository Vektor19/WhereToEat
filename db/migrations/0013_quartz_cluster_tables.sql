-- The trigger table references the job table; created after both above exist.
IF OBJECT_ID(N'dbo.QRTZ_TRIGGERS', N'U') IS NULL
    CREATE TABLE dbo.QRTZ_TRIGGERS
    (
        SCHED_NAME     VARCHAR(120)  NOT NULL,
        TRIGGER_NAME   VARCHAR(150)  NOT NULL,
        TRIGGER_GROUP  VARCHAR(150)  NOT NULL,
        JOB_NAME       VARCHAR(150)  NOT NULL,
        JOB_GROUP      VARCHAR(150)  NOT NULL,
        DESCRIPTION    VARCHAR(250)  NULL,
        NEXT_FIRE_TIME BIGINT        NULL,
        PREV_FIRE_TIME BIGINT        NULL,
        PRIORITY       INTEGER       NULL,
        TRIGGER_STATE  VARCHAR(16)   NOT NULL,
        TRIGGER_TYPE   VARCHAR(8)    NOT NULL,
        START_TIME     BIGINT        NOT NULL,
        END_TIME       BIGINT        NULL,
        CALENDAR_NAME  VARCHAR(200)  NULL,
        MISFIRE_INSTR  SMALLINT      NULL,
        JOB_DATA       VARBINARY(MAX) NULL,
        CONSTRAINT PK_QRTZ_TRIGGERS PRIMARY KEY CLUSTERED (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP),
        CONSTRAINT FK_QRTZ_TRIGGERS_QRTZ_JOB_DETAILS FOREIGN KEY (SCHED_NAME, JOB_NAME, JOB_GROUP)
            REFERENCES dbo.QRTZ_JOB_DETAILS (SCHED_NAME, JOB_NAME, JOB_GROUP)
    );
GO

-- The child trigger-type tables FK back to QRTZ_TRIGGERS; add the FKs once the parent exists.
IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = N'FK_QRTZ_CRON_TRIGGERS_QRTZ_TRIGGERS')
    ALTER TABLE dbo.QRTZ_CRON_TRIGGERS ADD CONSTRAINT FK_QRTZ_CRON_TRIGGERS_QRTZ_TRIGGERS
        FOREIGN KEY (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
        REFERENCES dbo.QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP) ON DELETE CASCADE;
GO

