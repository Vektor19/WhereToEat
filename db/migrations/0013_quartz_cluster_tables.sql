-- 0013_quartz_cluster_tables.sql
-- Step 12: the standard Quartz.NET SQL Server AdoJobStore tables (QRTZ_*), used in CLUSTERED mode.
--
-- These are the cluster bookkeeping tables that make a scheduled trigger fire on EXACTLY ONE worker
-- replica even when several replicas point at this same database: QRTZ_LOCKS gives Quartz the row
-- locks it uses to serialize scheduler instances, QRTZ_SCHEDULER_STATE tracks the live instances and
-- their check-in, and QRTZ_FIRED_TRIGGERS records the in-flight fire of each trigger so exactly one
-- node acquires it. Without these the worker cannot be clustered (the design's "single-fire under
-- clustering" requirement).
--
-- Schema source: the canonical Quartz.NET `tables_sqlServer.sql` for table prefix QRTZ_ (the default),
-- adapted to be IDEMPOTENT (each object guarded by IF NOT EXISTS) so it applies cleanly atop 0000-0012
-- and a re-run is a no-op (DbUp also journals it once). The price-median table is NOT here — it is
-- created in Step 7's 0010 and only POPULATED by the Step 12 nightly job.

IF OBJECT_ID(N'dbo.QRTZ_CALENDARS', N'U') IS NULL
    CREATE TABLE dbo.QRTZ_CALENDARS
    (
        SCHED_NAME    VARCHAR(120)  NOT NULL,
        CALENDAR_NAME VARCHAR(200)  NOT NULL,
        CALENDAR      VARBINARY(MAX) NOT NULL,
        CONSTRAINT PK_QRTZ_CALENDARS PRIMARY KEY CLUSTERED (SCHED_NAME, CALENDAR_NAME)
    );
GO

IF OBJECT_ID(N'dbo.QRTZ_CRON_TRIGGERS', N'U') IS NULL
    CREATE TABLE dbo.QRTZ_CRON_TRIGGERS
    (
        SCHED_NAME      VARCHAR(120) NOT NULL,
        TRIGGER_NAME    VARCHAR(150) NOT NULL,
        TRIGGER_GROUP   VARCHAR(150) NOT NULL,
        CRON_EXPRESSION VARCHAR(120) NOT NULL,
        TIME_ZONE_ID    VARCHAR(80)  NULL,
        CONSTRAINT PK_QRTZ_CRON_TRIGGERS PRIMARY KEY CLUSTERED (SCHED_NAME, TRIGGER_NAME, TRIGGER_GROUP)
    );
GO

IF OBJECT_ID(N'dbo.QRTZ_FIRED_TRIGGERS', N'U') IS NULL
