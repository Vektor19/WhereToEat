-- Helpful secondary indexes Quartz creates on the busy trigger tables (state scans / next-fire scans).
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_QRTZ_T_NEXT_FIRE_TIME' AND object_id = OBJECT_ID(N'dbo.QRTZ_TRIGGERS'))
    CREATE INDEX IDX_QRTZ_T_NEXT_FIRE_TIME ON dbo.QRTZ_TRIGGERS (SCHED_NAME, NEXT_FIRE_TIME);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_QRTZ_T_STATE' AND object_id = OBJECT_ID(N'dbo.QRTZ_TRIGGERS'))
    CREATE INDEX IDX_QRTZ_T_STATE ON dbo.QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_STATE);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_QRTZ_T_NEXT_FIRE_TIME_AND_STATE' AND object_id = OBJECT_ID(N'dbo.QRTZ_TRIGGERS'))
    CREATE INDEX IDX_QRTZ_T_NEXT_FIRE_TIME_AND_STATE ON dbo.QRTZ_TRIGGERS (SCHED_NAME, TRIGGER_STATE, NEXT_FIRE_TIME);
GO

IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'IDX_QRTZ_FT_TRIG_INST_NAME' AND object_id = OBJECT_ID(N'dbo.QRTZ_FIRED_TRIGGERS'))
    CREATE INDEX IDX_QRTZ_FT_TRIG_INST_NAME ON dbo.QRTZ_FIRED_TRIGGERS (SCHED_NAME, INSTANCE_NAME);
GO
